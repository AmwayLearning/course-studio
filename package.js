/*
 * Course Studio — turns a course made in the editor into an xAPI package:
 *   index.html, content.js, tincan.xml, runtime/*, assets/*, studio-source.json
 */
(function () {
  'use strict';
  const CS = window.CS = window.CS || {};
  const SITE = new URL('./', location.href);
  const runtimeCache = {};

  async function runtimeFile(name) {
    if (!runtimeCache[name]) {
      const r = await fetch(new URL('runtime/' + name, SITE).href, { cache: 'no-cache' });
      if (!r.ok) throw new Error('Could not load runtime/' + name + ' from the studio site.');
      runtimeCache[name] = await r.text();
    }
    return runtimeCache[name];
  }

  const xml = s => String(s == null ? '' : s).replace(/[<>&"']/g, c => ({ '<': '&lt;', '>': '&gt;', '&': '&amp;', '"': '&quot;', "'": '&apos;' }[c]));
  const html = s => String(s == null ? '' : s).replace(/[<>&"]/g, c => ({ '<': '&lt;', '>': '&gt;', '&': '&amp;', '"': '&quot;' }[c]));

  CS.activityIdFor = course => course.activityId || new URL('activities/' + encodeURIComponent(course.id), SITE).href;

  function walkAssets(obj, fn) {
    if (Array.isArray(obj)) return obj.map(v => walkAssets(v, fn));
    if (obj && typeof obj === 'object') { const o = {}; for (const k in obj) o[k] = walkAssets(obj[k], fn); return o; }
    if (typeof obj === 'string' && obj.startsWith('asset:')) return fn(obj.slice(6));
    return obj;
  }
  CS.usedAssets = function (course) {
    const used = new Set();
    walkAssets({ lessons: course.lessons, theme: course.theme }, h => (used.add(h), ''));
    return [...used];
  };

  const FONTS = {
    'Plus Jakarta Sans': 'Plus+Jakarta+Sans:wght@400;500;600;700;800',
    'Outfit': 'Outfit:wght@400;500;600;700;800',
    'Inter': 'Inter:wght@400;500;600;700;800',
    'Merriweather Sans': 'Merriweather+Sans:wght@400;500;600;700;800',
    'Nunito': 'Nunito:wght@400;500;600;700;800',
    'Poppins': 'Poppins:wght@400;500;600;700;800',
  };
  CS.FONTS = Object.keys(FONTS);

  CS.buildPackage = async function (course, getAsset) {
    const files = [];
    const activityId = CS.activityIdFor(course);
    const assets = course.assets || {};
    const used = CS.usedAssets(course);
    const assetPath = h => 'assets/' + h + '.' + ((assets[h] && assets[h].ext) || 'jpg');
    for (const h of used) {
      const blob = await getAsset(h);
      if (blob) files.push({ path: assetPath(h), data: blob, type: (assets[h] && assets[h].type) || 'image/jpeg' });
    }
    const data = {
      id: course.id, activityId, title: course.title, description: course.description || '', author: course.author || '', duration: course.duration || '',
      theme: walkAssets(course.theme || {}, h => assetPath(h)),
      settings: course.settings || {},
      lessons: walkAssets(course.lessons || [], h => assetPath(h)),
    };
    const font = (course.theme && course.theme.font) || 'Plus Jakarta Sans';
    const fontLink = FONTS[font] ? `<link rel="preconnect" href="https://fonts.googleapis.com">\n<link href="https://fonts.googleapis.com/css2?family=${FONTS[font]}&display=swap" rel="stylesheet">\n` : '';

    files.push({ path: 'index.html', type: 'text/html', data:
`<!doctype html>
<html lang="${html(course.lang || 'en')}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>${html(course.title)}</title>
${fontLink}<link rel="stylesheet" href="runtime/player.css">
</head>
<body>
<div id="app" aria-live="polite"></div>
<noscript>This course needs JavaScript turned on.</noscript>
<script src="content.js"></script>
<script src="runtime/xapi.js"></script>
<script src="runtime/player.js"></script>
</body>
</html>
` });
    files.push({ path: 'content.js', type: 'text/javascript', data: '/* Course content — generated by Course Studio. Edit the course in the studio, or change the text here. */\nwindow.COURSE = ' + JSON.stringify(data, null, 2) + ';\n' });
    files.push({ path: 'tincan.xml', type: 'text/xml', data:
`<?xml version="1.0" encoding="utf-8" ?>
<tincan xmlns="http://projecttincan.com/tincan.xsd">
  <activities>
    <activity id="${xml(activityId)}" type="http://adlnet.gov/expapi/activities/course">
      <name>${xml(course.title)}</name>
      <description lang="en-US">${xml(course.description || '')}</description>
      <launch lang="en-us">index.html</launch>
    </activity>
${(course.lessons || []).map(l => `    <activity id="${xml(activityId + '/lessons/' + l.id)}" type="http://adlnet.gov/expapi/activities/lesson">
      <name>${xml(l.title)}</name>
    </activity>`).join('\n')}
  </activities>
</tincan>
` });
    for (const f of ['player.js', 'player.css', 'xapi.js']) files.push({ path: 'runtime/' + f, type: f.endsWith('.css') ? 'text/css' : 'text/javascript', data: await runtimeFile(f) });
    const src = Object.assign({}, course); delete src._local;
    files.push({ path: 'studio-source.json', type: 'application/json', data: JSON.stringify(src, null, 2) });
    files.push({ path: 'README.txt', type: 'text/plain', data:
`${course.title}
${'='.repeat(Math.min(60, String(course.title).length))}

xAPI (Tin Can) course made with Course Studio.

Upload this zip to any LMS that supports xAPI / Tin Can, or open index.html in a browser.

Files
  index.html            the page the LMS launches
  tincan.xml            the xAPI manifest (course activity ID, name, launch file)
  content.js            all course text, lessons and questions
  runtime/player.js     shows the course and its interactions
  runtime/player.css    the look of the course
  runtime/xapi.js       sends xAPI statements and saves the learner's place
  assets/               pictures used in the course
  studio-source.json    lets you upload this zip back into Course Studio and keep editing

Course activity ID: ${activityId}
` });
    return files;
  };

  CS.zipFiles = async function (files, onProgress) {
    const zip = new JSZip();
    files.forEach(f => zip.file(f.path, f.data));
    return zip.generateAsync({ type: 'blob', compression: 'DEFLATE', compressionOptions: { level: 6 } }, m => onProgress && onProgress(m.percent / 100));
  };
})();
